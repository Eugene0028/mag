package securetransfer.measurement;

/**
 * Общий контракт системного счётчика процессорных циклов.
 *
 * <p>Создавайте, читайте и закрывайте экземпляр в одном потоке. Разность двух
 * чтений включает служебные затраты обращения к системному счётчику.
 * Доступность и точный смысл циклов определяются ОС и оборудованием.</p>
 */
public interface CpuCycleCounter extends AutoCloseable {
    /**
     * Возвращает накопленное число циклов потока.
     *
     * <p>Значение может представлять беззнаковое число в битах Java long.
     * Начало отсчёта зависит от реализации; сравнивайте разности показаний.</p>
     *
     * @return текущее число циклов
     * @throws UnsupportedOperationException если системный счётчик недоступен
     * @throws IllegalStateException если счётчик используется неверно
     */
    long readCurrentThreadCycles();

    /**
     * Описывает источник измерения и учитываемую им работу потока.
     *
     * @return описание системного счётчика
     */
    String getDescription();

    /** Освобождает ресурсы счётчика; реализации без ресурсов используют пустой метод. */
    @Override
    default void close() {
    }
}
