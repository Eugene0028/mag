package securetransfer.rgz.measurement;

/** Интервалы прошедшего времени; вложенные интервалы нельзя складывать с общими. */
public enum TransferPhase {
    /** Подготовка серверного MQV до ожидания подключения, включая проверки файлов. */
    PREPARATION,
    /** Установка TCP-соединения на стороне отправителя. */
    CONNECTION,
    /** MQV, проверки доверия, SHA3 и взаимное подтверждение ключа после подключения. */
    KEY_ESTABLISHMENT,
    /** Создание и установка ключа и IV потокового шифра. */
    CIPHER_SETUP,
    /** Суммарная длительность вызовов processBytes без HMAC и ввода-вывода. */
    CIPHER,
    /** Обновление HMAC внутри обработки порций; финальный тег учитывается в общем интервале. */
    AUTHENTICATION,
    /** Чтение или запись файла внутри цикла обработки, без force и открытия файла. */
    DISK_IO,
    /** Вызовы сетевых потоков, flush и ожидание подтверждения по часам, включая блокировки. */
    NETWORK_IO,
    /** От подготовки заголовка до отправки или получения подтверждения всего файла. */
    TRANSFER_ELAPSED
}
