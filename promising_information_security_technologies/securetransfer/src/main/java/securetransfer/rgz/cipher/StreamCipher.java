package securetransfer.rgz.cipher;

/**
 * Общие действия потокового шифра для обработки данных порциями.
 *
 * <p>Сначала вызовите {@link #initialize(byte[], byte[])}, затем передавайте
 * очередные порции данных в {@link #processBytes(byte[], int, int, byte[], int)}.
 * Объект сохраняет позицию в ключевом потоке между вызовами. Обработка данных
 * целиком и обработка тех же данных порциями должны давать одинаковый результат.</p>
 *
 * <p>Шифрование и расшифрование выполняются одной операцией: входные байты
 * складываются с ключевым потоком через XOR. Для расшифрования нужен отдельный
 * объект с теми же ключом и IV, начинающий обработку с первого байта потока.</p>
 *
 * <p>Один объект используется последовательно в одном потоке выполнения.
 * Для нового сообщения с тем же ключом необходим новый IV.</p>
 */
public interface StreamCipher {
    /**
     * Возвращает название алгоритма для вывода и результатов измерений.
     *
     * @return название алгоритма, например {@code HC-128} или {@code Salsa20/20}
     */
    String getName();

    /**
     * Возвращает длину ключа, принимаемого данной реализацией.
     *
     * @return требуемое количество байтов ключа
     */
    int getKeyLengthBytes();

    /**
     * Возвращает длину вектора инициализации, принимаемого данной реализацией.
     *
     * @return требуемое количество байтов IV
     */
    int getInitializationVectorLengthBytes();

    /**
     * Подготавливает состояние шифра по ключу и IV к обработке первого байта.
     *
     * <p>Метод выполняет всю подготовку ключа и IV до своего завершения.
     * Повторный вызов заменяет прежнее состояние и начинает новый поток.
     * Массивы аргументов не изменяются; если реализация хранит их после вызова,
     * она сохраняет собственные копии.</p>
     *
     * @param secretKey секретный ключ длиной {@link #getKeyLengthBytes()} байтов
     * @param initializationVector IV длиной {@link #getInitializationVectorLengthBytes()} байтов
     * @throws NullPointerException если ключ или IV равен {@code null}
     * @throws IllegalArgumentException если длина ключа или IV неверна
     */
    void initialize(byte[] secretKey, byte[] initializationVector);

    /**
     * Шифрует или расшифровывает указанную порцию данных, продолжая ключевой поток.
     *
     * <p>Читает {@code byteCount} байтов с позиции {@code inputOffset}
     * и записывает ровно столько же байтов с позиции {@code outputOffset}.
     * Длина порции может быть любой: реализация сохраняет неиспользованный
     * остаток ключевого потока. Нулевая длина не меняет состояние шифра.</p>
     *
     * <p>Входной и выходной массивы могут совпадать. При совпадающих смещениях
     * данные заменяются результатом в том же участке. При разных смещениях
     * участки одного массива не должны пересекаться. Остальные байты выходного
     * массива и входные байты вне участка результата не изменяются.</p>
     *
     * @param inputBytes массив исходных данных
     * @param inputOffset смещение первого обрабатываемого байта во входном массиве
     * @param byteCount количество обрабатываемых байтов
     * @param outputBytes массив для результата
     * @param outputOffset смещение первого записываемого байта в выходном массиве
     * @throws IllegalStateException если шифр ещё не инициализирован
     * @throws NullPointerException если входной или выходной массив равен {@code null}
     * @throws IndexOutOfBoundsException если смещение или длина отрицательны
     *         либо участок выходит за границы массива
     * @throws IllegalArgumentException если участки одного массива пересекаются
     *         при разных смещениях
     */
    void processBytes(
            byte[] inputBytes,
            int inputOffset,
            int byteCount,
            byte[] outputBytes,
            int outputOffset
    );
}
